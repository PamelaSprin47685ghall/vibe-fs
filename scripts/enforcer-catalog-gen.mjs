#!/usr/bin/env node
// enforcer-catalog-gen.mjs — extract the 120-rule catalog from SSOT/15.md into
// F# source. ENFORCER-180 step 1: the Rule Catalog is the single source of
// truth, and everything else is generated from it. A hand-written parallel list
// is the exact drift ENFORCER-170 forbids.
//
//   node scripts/enforcer-catalog-gen.mjs --write   (rewrite the generated .fs)
//   node scripts/enforcer-catalog-gen.mjs           (report only)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SSOT = resolve('SSOT/15.md')
const OUT = resolve('next/Domain/EnforcerCatalog.gen.fs')

const text = readFileSync(SSOT, 'utf8')
const lines = text.split('\n')

const rules = []
let current = null
let pendingFamily = ''

for (const line of lines) {
  // Family header (`## A.`) names the section the NEXT rules belong to.
  // Checked before the `!current` guard: the first family header precedes the
  // first rule, and skipping it there would leave family A empty.
  const family = line.match(/^## ([A-Z])\./)
  if (family) {
    pendingFamily = family[1]
    continue
  }

  const header = line.match(/^### (ENF-[A-Z]\d{2}) — `([a-z0-9-]+)`\s*$/)
  if (header) {
    if (current) rules.push(current)
    current = { id: header[1], field: header[2], score: '', nudge: '', family: pendingFamily }
    continue
  }
  if (!current) continue

  // Section separators and other chrome.
  if (line.trim() === '---' || line.startsWith('#') || line.startsWith('```')) continue

  const score = line.match(/^Score when: (.*)$/)
  if (score) {
    current.score += score[1].trim()
    continue
  }
  const nudge = line.match(/^Nudge: (.*)$/)
  if (nudge) {
    current.nudge += nudge[1].trim()
    continue
  }
  // Continuation lines of the previous score/nudge paragraph.
  if (current.score && !current.nudge && line.trim() !== '') {
    current.score += ' ' + line.trim()
  } else if (current.nudge && line.trim() !== '') {
    current.nudge += ' ' + line.trim()
  }
}
if (current) rules.push(current)

if (rules.length !== 120) {
  console.error(`expected 120 rules, extracted ${rules.length}`)
  process.exit(1)
}

const esc = (s) => s.replace(/"""/g, '\\"\\"\\"')

const entries = rules
  .map(
    (r, i) =>
      `        {| RuleId = "enforcement-${r.id.toLowerCase().replace('enf-', '')}"; FieldName = "${r.field}"; Family = "${r.family}"; ScoreWhen = """${esc(r.score)}"""; Nudge = """${esc(r.nudge)}"""; CatalogOrdinal = ${i + 1} |}`,
  )
  .join('\n')

const out = `// GENERATED by scripts/enforcer-catalog-gen.mjs — DO NOT EDIT BY HAND.
// ENFORCER-170: the Rule Catalog in SSOT/15.md is the single source of truth.
// FieldName is the provider-visible blog tool argument; ScoreWhen is the schema
// description; Nudge is the fixed rendered text (ENFORCER-100).

namespace Wanxiangshu.Next.Domain

module EnforcerCatalogData =

    /// 120 项规则，从 SSOT/15.md 提取（ENFORCER-180 第 1 步生成器）。
    /// 每项：RuleId / FieldName / Family / ScoreWhen / Nudge / CatalogOrdinal。
    let rules : {| RuleId: string; FieldName: string; Family: string; ScoreWhen: string; Nudge: string; CatalogOrdinal: int |} list =
        [
${entries}
        ]
`

if (process.argv.includes('--write')) {
  writeFileSync(OUT, out)
  console.log(`wrote ${rules.length} rules to ${OUT}`)
} else {
  console.log(`${rules.length} rules extracted (${OUT} dry run)`)
}
