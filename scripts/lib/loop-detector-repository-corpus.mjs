import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')

const sourceDocumentExtensions = new Set([
  '.c', '.cc', '.cpp', '.cxx', '.h', '.hh', '.hpp', '.hxx',
  '.cu', '.cuh', '.cl', '.comp', '.glsl', '.wgsl', '.metal',
  '.cs', '.fs', '.fsi', '.fsx', '.fsproj', '.java', '.kt', '.kts', '.swift',
  '.go', '.rs', '.py', '.pyi', '.rb', '.php', '.lua', '.pl',
  '.js', '.mjs', '.cjs', '.jsx', '.ts', '.tsx', '.svelte',
  '.css', '.scss', '.sh', '.bash', '.zsh', '.fish', '.ps1', '.bat',
  '.cmake', '.mk', '.nix', '.gradle', '.props', '.pro', '.ld', '.idl',
  '.jinja', '.gbnf', '.tmpl', '.template', '.schema', '.in',
  '.toml', '.yaml', '.yml', '.md', '.mdx', '.rst', '.adoc',
])

const sourceDocumentNames = new Set([
  'APPLIES-TO', 'AUTHORS', 'CMakeLists.txt', 'CODEOWNERS', 'Dockerfile', 'LICENSE', 'Makefile',
])

const excludedSegments = new Set([
  'build', 'deps', 'dist', 'fixture', 'fixtures', 'generated', 'node_modules',
  'golden', 'goldens', 'snapshot', 'snapshots', 'testdata',
  'third-party', 'third_party', 'vendor', 'vendors',
])

const generatedMarkers = [
  'auto-generated',
  'autogenerated',
  'do not edit',
  'generated with',
  'pre-computed rotation matrices',
]

const isSourceDocumentPath = (relPath) => {
  const normalized = relPath.replaceAll('\\', '/')
  const segments = normalized.split('/')
  if (segments.some((segment) => excludedSegments.has(segment.toLowerCase()))) return false

  const name = segments.at(-1)
  return sourceDocumentNames.has(name) || sourceDocumentExtensions.has(path.extname(name).toLowerCase())
}

const isGeneratedText = (text) => {
  const prefix = text.slice(0, 4096).toLowerCase()
  return generatedMarkers.some((marker) => prefix.includes(marker))
}

const repositoryTextEntries = (root = defaultRoot) => {
  const decoder = new TextDecoder('utf-8', { fatal: true })
  const paths = execFileSync('git', ['-C', root, 'ls-files', '--cached', '-z'])
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .filter(isSourceDocumentPath)

  const readable = []
  for (const relPath of paths) {
    const file = path.join(root, relPath)
    try {
      const text = decoder.decode(readFileSync(file))
      if (!isGeneratedText(text)) readable.push({ file, text })
    } catch {
      // Strict UTF-8 is required for source/document corpus membership.
    }
  }
  return readable
}

export const loopDetectorRepositoryInputFiles = (root = defaultRoot) =>
  repositoryTextEntries(root).map(({ file }) => file)

export const loopDetectorRepositoryTexts = (root = defaultRoot) =>
  repositoryTextEntries(root).map(({ text }) => text)
